// SQL Server DB Script Exporter - scripts the schema and/or data of an MSSQL database: one .sql file per
// object (UTF-16 LE with BOM, CRLF), or everything in a single file.
//
// Requires the .NET 10 SDK. Run with run.ps1 / run.sh, or: dotnet run SqlServerDbScriptExporter.cs -- --help
// Or publish it as an app with publish.ps1 / publish.sh (--help for the options; not native AOT, which SMO
// does not support).
//
// Without arguments it asks for everything (server, login, database, what to script and where) and remembers
// the answers in SqlServerDbScriptExporter.settings.json next to this file (or the published .exe) - never the
// password. With arguments it asks nothing (except the password, when DB_EXPORT_PASSWORD is not set), for
// scripted runs.
//
// One file per object (relative to the output folder):
//   Table/     <schema>.<name>.Table.sql                  table + keys, constraints, indexes, triggers
//   SP/        <schema>.<name>.StoredProcedure.sql
//   UDF/       <schema>.<name>.UserDefinedFunction.sql
//   UDT/       <schema>.<name>.UserDefinedTableType.sql
//   Views/     <schema>.<name>.View.sql
//   Data/      <schema>.<name>.Table.sql                  table data (INSERTs); the folder name is an option
//
// What is scripted: the entire database, or specific objects (chosen from a list grouped by type). The same
// choice covers the schema and the data of the chosen tables. Files of objects that exist but are not chosen
// are left alone.
//
// Single file (<database>.sql by default), in an order that runs on an empty database: table types; tables,
// functions, views and procedures in dependency order (tables without their foreign keys and triggers); the
// data; then the foreign keys and triggers, so the rows can be inserted in any order without firing triggers.
//
// Other files in the folders (hand-written alters, rollbacks, sub folders, ...) are never touched.
// A file counts as generated by its name alone (<schema>.<name>.<suffix>.sql), so never give a
// hand-written file such a name (e.g. "dbo.X.Rollback.Table.sql"): pruning would delete it. Use a
// different last part instead, as the existing ones do ("dbo.X.Alter.sql", "dbo.X.Rollback_Y.sql").
// A file is only rewritten when its content changed (the "Script Date" headers are ignored; with data
// also the row order, which SMO does not fix), so a re-run produces a clean git diff.
//
// Procedures, functions and views use CREATE, or CREATE OR ALTER when chosen (--create-or-alter);
// tables, their triggers and table types always use CREATE.
//
// Not scripted: schemas, sequences, synonyms, alias types (CREATE TYPE ... FROM), database triggers.

