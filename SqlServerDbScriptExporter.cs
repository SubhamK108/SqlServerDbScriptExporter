int Exit(int exitCode)
{
    DeleteTempFiles();
    lock (tempFiles)
    {
        foreach (var path in tempFiles)
        {
            AnsiConsole.MarkupLine($"[yellow]Could not delete the temporary file[/] {Markup.Escape(path)}");
        }
    }

    if (pauseAtExit)
    {
        Pause();
    }

    return exitCode;
}

// A new temporary file in directory, for fileName: next to it, so it can replace the file in one move. Its name
// (".<file name>.<32 hex digits>.tmp") is never a <schema>.<name>.<suffix>.sql, so it is never taken for a script.
string TempFile(string directory, string fileName)
{
    var path = Path.Combine(directory, $".{fileName}.{Guid.NewGuid():N}.tmp");
    lock (tempFiles)
    {
        tempFiles.Add(path);
    }

    return path;
}

void DeleteTemp(string path)
{
    DeleteQuietly(path);
    if (!File.Exists(path))
    {
        lock (tempFiles)
        {
            tempFiles.Remove(path);
        }
    }
}

void DeleteTempFiles()
{
    lock (tempFiles)
    {
        foreach (var path in tempFiles)
        {
            DeleteQuietly(path);
        }

        tempFiles.RemoveAll(path => !File.Exists(path));
    }
}

List<Table> Tables() => allTables ??= ObjectsIn(database, "Table").Cast<Table>().ToList();

IEnumerable<ScriptSchemaObjectBase> ObjectsOf(string folder) => folder == "Table" ? Tables() : ObjectsIn(database, folder);

ScriptingOptions OptionsFor(ScriptSchemaObjectBase obj) => obj is StoredProcedure or UserDefinedFunction or View ? moduleOptions : schemaOptions;

// The chosen objects of one type: all of them (the entire database) or the
// selected ones (--objects / the interactive list). The same choice covers the schema and the data of tables.
List<T> Chosen<T>(string folder, IEnumerable<T> objects) where T : ScriptSchemaObjectBase
{
    var list = objects.ToList();
    seenObjects.UnionWith(list.Select(o => ObjectKey(o.Schema, o.Name)));
    return list.Where(o => options.Selected(folder, o.Schema, o.Name)).ToList();
}

// File names of the objects that exist but are not chosen: their files are left alone (not leftovers).
HashSet<string> NotChosen<T>(IEnumerable<T> all, IEnumerable<T> chosen, string suffix) where T : ScriptSchemaObjectBase =>
    all.Except(chosen).Select(o => FileName(o.Schema, o.Name, suffix)).ToHashSet(StringComparer.OrdinalIgnoreCase);

string DataTitle() => $"{options.DataFolder} (data)";

void ExportSchema(ProgressTask task, string folder, string suffix, Type type)
{
    // Reading the definitions is the slow part, so it runs inside the folder's bar (as an animated, unknown amount).
    Begin(task);
    List<ScriptSchemaObjectBase> all;
    try
    {
        // Fetch all scripting properties in a few queries instead of one round trip per object.
        database.PrefetchObjects(type, schemaOptions);
        all = ObjectsOf(folder).ToList();
    }
    catch (Exception ex) when (IsSqlError(ex))
    {
        FailTask(task, folder, ex);
        return;
    }

    var list = Chosen(folder, all);
    Measure(task, list.Count);
    var directory = Path.Combine(outputRoot, folder);
    var existing = ExistingFiles(directory, suffix);
    var generated = NotChosen(all, list, suffix);
    foreach (var obj in list)
    {
        var fileName = FileName(obj.Schema, obj.Name, suffix);
        if (!generated.Add(fileName))
        {
            // Only possible with a case-sensitive collation (e.g. dbo.GetX and dbo.getx): Windows sees one file.
            report.Add(folder, Outcome.Failed, fileName, "another object has the same name apart from upper/lower case; only the first is written");
        }
        else
        {
            try
            {
                Save(folder, directory, fileName, existing, writer =>
                {
                    ScriptObject(writer, obj, suffix, OptionsFor(obj));
                    return true;
                });
            }
            catch (Exception ex)
            {
                Fail(folder, fileName, ex);
            }
        }

        task.Increment(1);
    }

    Finish(task);
    Prune(folder, existing, generated);
}

void ExportData(ProgressTask task)
{
    var folder = options.DataFolder;
    Begin(task);
    List<Table> all;
    List<(Table Table, long Weight)> dataTables;
    try
    {
        all = Tables();
        // Weighted by row count (from the table's statistics), so a big table moves the bar more than a small one.
        dataTables = Chosen("Table", all).Select(t => (t, Weight(t))).ToList();
    }
    catch (Exception ex) when (IsSqlError(ex))
    {
        FailTask(task, folder, ex);
        return;
    }

    Measure(task, dataTables.Sum(t => t.Weight), Unit.Rows);
    var directory = Path.Combine(outputRoot, folder);
    var existing = ExistingFiles(directory, "Table");
    // Only the files of tables that are gone (or chosen and empty) are leftovers.
    var generated = NotChosen(all, dataTables.Select(t => t.Table), "Table");
    double done = 0;
    foreach (var (table, weight) in dataTables)
    {
        var fileName = FileName(table.Schema, table.Name, "Table");
        if (!generated.Add(fileName))
        {
            report.Add(folder, Outcome.Failed, fileName, "another table has the same name apart from upper/lower case; only the first is written");
        }
        else
        {
            try
            {
                // SMO selects the rows without an ORDER BY, so only a change in the rows themselves counts.
                if (!Save(folder, directory, fileName, existing, writer => ScriptData(writer, table, weight, task), ignoreLineOrder: true))
                {
                    // The existing file (if any) holds rows that are gone: leave it to Prune.
                    report.Add(folder, Outcome.Skipped, fileName, "table is empty");
                    generated.Remove(fileName);
                }
            }
            catch (Exception ex)
            {
                Fail(folder, fileName, ex);
            }
        }

        done += weight;
        task.Value = done;
    }

    Finish(task);
    Prune(folder, existing, generated);
}

void ExportSingleFile(ProgressContext progress)
{
    // The report has no folder for the single file.
    const string folder = "";
    var fileName = Path.GetFileName(singleFilePath);
    var includesTables = includedSchemaFolders.Any(f => f.Folder == "Table");
    var readTask = AddTask(progress, "Reading definitions");
    var orderTask = AddTask(progress, "Ordering by dependencies");
    var schemaTask = options.IncludeSchema ? AddTask(progress, "Schema") : null;
    var dataTask = includesData ? AddTask(progress, "Data") : null;
    var keysTask = includesTables ? AddTask(progress, "Foreign keys and triggers") : null;
    // The report entries from here on belong to this file (for the warning at its top, see below).
    var firstEntry = report.Entries.Count;

    Begin(readTask);
    List<ScriptSchemaObjectBase> types;
    List<ScriptSchemaObjectBase> objects;
    List<Table> dataTables = [];
    try
    {
        foreach (var (_, _, type) in includedSchemaFolders)
        {
            database.PrefetchObjects(type, schemaOptions);
        }

        // Table types first: they depend on nothing else here, and procedures and functions use them.
        types = includedSchemaFolders.Where(f => f.Folder == "UDT").SelectMany(f => Chosen(f.Folder, ObjectsOf(f.Folder))).ToList();
        objects = includedSchemaFolders.Where(f => f.Folder != "UDT").SelectMany(f => Chosen(f.Folder, ObjectsOf(f.Folder))).ToList();
        if (includesData)
        {
            dataTables = Chosen("Table", Tables());
        }
    }
    catch (Exception ex) when (IsSqlError(ex))
    {
        FailTask(readTask, folder, ex, fileName);
        foreach (var task in new[] { orderTask, schemaTask, dataTask, keysTask })
        {
            Skip(task);
        }

        return;
    }

    Finish(readTask);

    // Tables, functions, views and procedures so that each comes after what it uses (functions in a table's
    // defaults, schema-bound views, ...); the data with parent tables first, so it also loads into a database
    // that already has the foreign keys.
    Begin(orderTask);
    try
    {
        SqlSmoObject[] toOrder = [.. objects.Cast<SqlSmoObject>().Union(dataTables)];
        if (toOrder.Length > 0)
        {
            var walker = new DependencyWalker(server);
            var ordered = walker.WalkDependencies(walker.DiscoverDependencies(toOrder, DependencyType.Parents));
            Dictionary<string, int> position = new(StringComparer.OrdinalIgnoreCase);
            foreach (var node in ordered)
            {
                position.TryAdd(node.Urn.ToString(), position.Count);
            }

            int Position(SqlSmoObject obj) => position.TryGetValue(obj.Urn.ToString(), out var p) ? p : int.MaxValue;
            objects = [.. objects.OrderBy(Position)];
            dataTables = [.. dataTables.OrderBy(Position)];
        }
    }
    catch (Exception ex) when (IsSqlError(ex))
    {
        report.Add(folder, Outcome.Warning, fileName, $"could not order by dependencies ({ex.GetBaseException().Message}); used tables, functions, views, procedures");
        objects = [.. objects.OrderBy(o => o switch { Table => 0, UserDefinedFunction => 1, View => 2, _ => 3 })];
    }

    Finish(orderTask);

    // The script goes to a temporary file as it is made (a big database does not fit in memory). The warning
    // about failed objects is only known at the end; it then goes in front of it in the real file.
    var bodyPath = TempFile(Path.GetDirectoryName(singleFilePath)!, fileName);
    try
    {
        using (var body = new StreamWriter(bodyPath, append: false, fileEncoding))
        {
            if (schemaTask is not null)
            {
                Begin(schemaTask);
                Measure(schemaTask, types.Count + objects.Count);
                foreach (var obj in types.Concat(objects))
                {
                    try
                    {
                        ScriptObject(body, obj, obj.GetType().Name, obj is Table ? singleFileTableOptions : OptionsFor(obj));
                    }
                    catch (Exception ex)
                    {
                        Fail(folder, $"{obj.Schema}.{obj.Name}", ex);
                    }

                    schemaTask.Increment(1);
                }

                Finish(schemaTask);
            }

            if (dataTask is not null)
            {
                Begin(dataTask);
                var weights = dataTables.Select(Weight).ToList();
                Measure(dataTask, weights.Sum(), Unit.Rows);
                double done = 0;
                for (var i = 0; i < dataTables.Count; i++)
                {
                    var table = dataTables[i];
                    try
                    {
                        ScriptData(body, table, weights[i], dataTask);
                    }
                    catch (Exception ex)
                    {
                        // The rows written before the error stay; the warning at the top says the data is incomplete.
                        Fail(folder, $"{table.Schema}.{table.Name} (data)", ex);
                    }

                    done += weights[i];
                    dataTask.Value = done;
                }

                Finish(dataTask);
            }

            if (keysTask is not null)
            {
                var tables = objects.OfType<Table>().ToList();
                Begin(keysTask);
                Measure(keysTask, tables.Count, Unit.Tables);
                foreach (var table in tables)
                {
                    try
                    {
                        foreach (var foreignKey in table.ForeignKeys.Cast<ForeignKey>())
                        {
                            AppendBatches(body, foreignKey.Script(schemaOptions));
                        }

                        foreach (var trigger in table.Triggers.Cast<Trigger>())
                        {
                            var batches = trigger.Script(schemaOptions);
                            body.Write($"/****** Object:  Trigger [{table.Schema}].[{trigger.Name}]    Script Date: {scriptDate} ******/{Eol}");
                            AppendBatches(body, batches);
                        }
                    }
                    catch (Exception ex)
                    {
                        Fail(folder, $"{table.Schema}.{table.Name} (foreign keys and triggers)", ex);
                    }

                    keysTask.Increment(1);
                }

                Finish(keysTask);
            }
        }

        // A script with objects missing says so at the top, so nobody runs it thinking it is complete.
        var failures = report.Entries.Skip(firstEntry).Where(e => e.Outcome == Outcome.Failed).ToList();
        if (failures.Count > 0)
        {
            report.Add(folder, Outcome.Warning, fileName, $"incomplete: {failures.Count} failed, listed at the top of the file");
        }

        var existing = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        if (File.Exists(singleFilePath))
        {
            existing[fileName] = singleFilePath;
        }

        // With data the row order is not fixed (see ScriptData), so only a change in the lines themselves counts.
        Save(folder, Path.GetDirectoryName(singleFilePath)!, fileName, existing, writer =>
        {
            if (failures.Count > 0)
            {
                writer.Write($"/* WARNING: this script is incomplete. These could not be scripted (completely):{Eol}");
                foreach (var failure in failures)
                {
                    writer.Write($"     {failure.File}: {failure.Detail?.Replace("*/", "* /")}{Eol}");
                }

                writer.Write($"*/{Eol}");
            }

            using var reader = new StreamReader(bodyPath, fileEncoding);
            CopyText(reader, writer);
            return true;
        }, ignoreLineOrder: options.IncludeData, allHeaders: true);
    }
    catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
    {
        Fail(folder, fileName, ex);
    }
    finally
    {
        DeleteTemp(bodyPath);
    }
}

// An object's script: the "/****** Object: ... ******/" header line, then its batches, each followed by GO.
// Scripted before anything is written, so a failing object leaves nothing half-written.
void ScriptObject(TextWriter writer, ScriptSchemaObjectBase obj, string headerType, ScriptingOptions scriptingOptions)
{
    var batches = ((IScriptable)obj).Script(scriptingOptions);
    writer.Write($"/****** Object:  {headerType} [{obj.Schema}].[{obj.Name}]    Script Date: {scriptDate} ******/{Eol}");
    AppendBatches(writer, batches);
}

// Writes a table's rows as INSERT statements, with a GO after every DataBatchSize statements, as they are read
// (a big table does not fit in memory). Returns false when the table is empty. Moves the task by up to weight
// (the estimated row count).
bool ScriptData(TextWriter writer, Table table, long weight, ProgressTask task)
{
    var count = 0;
    long rows = 0;
    SqlSmoObject[] target = [table];
    foreach (var statement in dataScripter.EnumScript(target))
    {
        writer.Write(statement);
        writer.Write(Eol);
        if (++count % DataBatchSize == 0)
        {
            writer.Write($"GO{Eol}");
        }

        // The row count is an estimate: never move past this table's share.
        if (rows < weight && statement.StartsWith("INSERT", StringComparison.Ordinal))
        {
            rows++;
            task.Increment(1);
        }
    }

    if (count == 0)
    {
        return false;
    }

    if (count % DataBatchSize != 0)
    {
        writer.Write($"GO{Eol}");
    }

    return true;
}

// Writes a file through a temporary one next to it: write fills it (false: nothing to write, e.g. an empty
// table; the existing file is left as it is). The file is only replaced when the content changed. Returns
// whether there was something to write.
bool Save(string folder, string directory, string fileName, Dictionary<string, string> existing, Func<TextWriter, bool> write,
    bool ignoreLineOrder = false, bool allHeaders = false)
{
    Directory.CreateDirectory(directory);
    var path = Path.Combine(directory, fileName);
    var temp = TempFile(directory, fileName);
    try
    {
        using (var writer = new StreamWriter(temp, append: false, fileEncoding))
        {
            if (!write(writer))
            {
                return false;
            }
        }

        if (existing.TryGetValue(fileName, out var existingPath))
        {
            if (SameContent(existingPath, temp, ignoreLineOrder, allHeaders))
            {
                if (existingPath != path)
                {
                    // Same content, but the object name's casing changed.
                    File.Move(existingPath, path);
                    report.Add(folder, Outcome.Renamed, fileName, $"was {Path.GetFileName(existingPath)}");
                }
                else
                {
                    report.Add(folder, Outcome.Unchanged, fileName);
                }

                return true;
            }

            if (existingPath != path)
            {
                File.Delete(existingPath);
            }
        }

        File.Move(temp, path, overwrite: true);
        report.Add(folder, existingPath is null ? Outcome.Added : Outcome.Updated, fileName);
        return true;
    }
    finally
    {
        DeleteTemp(temp);
    }
}

void Prune(string folder, Dictionary<string, string> existing, HashSet<string> generated)
{
    foreach (var (fileName, path) in existing)
    {
        if (generated.Contains(fileName))
        {
            continue;
        }

        if (options.Prune)
        {
            try
            {
                File.Delete(path);
                report.Add(folder, Outcome.Deleted, fileName);
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                report.Add(folder, Outcome.Failed, fileName, $"could not delete: {ex.Message}");
            }
        }
        else
        {
            report.Add(folder, Outcome.Orphan, path);
        }
    }
}

void Fail(string folder, string fileName, Exception ex) => report.Add(folder, Outcome.Failed, fileName, ex.GetBaseException().Message);

// A step that could not read what it needs: report it and leave its files alone (no pruning, nothing written).
void FailTask(ProgressTask task, string folder, Exception ex, string? fileName = null)
{
    report.Add(folder, Outcome.Failed, fileName ?? "(could not read the objects, no files changed)", ex.GetBaseException().Message);
    task.IsIndeterminate = false;
    task.StopTask();
    task.State.Update<TaskPhase>(StatusColumn.PhaseKey, _ => TaskPhase.Failed);
}

// Asks for the connection and what to script, with the last run's answers as defaults. Returns the open
// connection, or null (with the exit code) when connecting failed or the user cancelled.
static Server? AskInteractively(Options options, string settingsPath, out int exitCode)
{
    const string RetryConnection = "Change the connection details and try again";
    const string Direct = "Enter the database name and connect to it directly (for a login without access to master)";
    const string RetryDatabase = "Try another database";
    const string Cancel = "Cancel";

    exitCode = 0;
    var settings = Settings.Load(settingsPath);
    // The database of the last run (settings.Database is replaced by this run's once connected).
    var previousDatabase = settings.Database;

    AnsiConsole.Write(new Rule($"[bold]{AppName}[/] [grey]{Markup.Escape(Options.Version)}[/]").LeftJustified());
    AnsiConsole.MarkupLine("[grey]Scripts the schema and data of an MSSQL database. Enter keeps the suggested value.[/]");
    AnsiConsole.WriteLine();

    // The connection and the database. A failure shows why and lets you change the answers (they stay as defaults).
    options.Server = settings.Server;
    options.User = settings.User;
    options.TrustServerCertificate = settings.TrustServerCertificate;
    options.Database = settings.Database;
    var password = EnvironmentPassword();
    if (password is not null)
    {
        AnsiConsole.MarkupLine($"[grey]Using the password from {Options.PasswordEnvVar}.[/]");
    }

    Server? server = null;
    while (server is null)
    {
        options.Server = AskText("Server", options.Server);
        options.User = AskText("SQL login", options.User);
        options.TrustServerCertificate = AnsiConsole.Confirm(
            "Trust the server certificate? [grey](self-signed, typical for local servers)[/]", options.TrustServerCertificate);
        options.Password = password ?? AnsiConsole.Prompt(new TextPrompt<string>($"Password for [blue]{Markup.Escape(options.User)}[/]:").Secret());

        var (databases, connectError, listError) = ListDatabases(options);
        if (listError is not null)
        {
            AnsiConsole.MarkupLine($"[yellow]Connected, but could not list the databases:[/] [grey]{Markup.Escape(listError)}[/]");
        }

        if (connectError is not null)
        {
            AnsiConsole.MarkupLine($"[red]Could not connect:[/] {Markup.Escape(connectError)}");
            var next = AnsiConsole.Prompt(new SelectionPrompt<string>().Title("What now?").AddChoices(RetryConnection, Direct, Cancel));
            if (next == Cancel)
            {
                exitCode = 1;
                return null;
            }

            if (next == RetryConnection)
            {
                // The password (or DB_EXPORT_PASSWORD) may be what is wrong, so ask for it again.
                password = null;
                continue;
            }
        }

        while (true)
        {
            if (databases.Count > 0)
            {
                var current = options.Database;
                options.Database = AnsiConsole.Prompt(new SelectionPrompt<string>()
                    .Title("Database:")
                    .PageSize(15)
                    .EnableSearch()
                    .UseConverter(Markup.Escape)
                    .AddChoices(databases.OrderByDescending(d => d.Equals(current, StringComparison.OrdinalIgnoreCase))));
                AnsiConsole.MarkupLine($"Database: [blue]{Markup.Escape(options.Database)}[/]");
            }
            else
            {
                options.Database = AskText("Database", options.Database);
            }

            (server, var openError) = OpenDatabase(options);
            if (server is not null)
            {
                break;
            }

            AnsiConsole.MarkupLine($"[red]Could not open {Markup.Escape(options.Database)}:[/] {Markup.Escape(openError ?? "")}");
            var next = AnsiConsole.Prompt(new SelectionPrompt<string>().Title("What now?").AddChoices(RetryDatabase, RetryConnection, Cancel));
            if (next == Cancel)
            {
                exitCode = 1;
                return null;
            }

            if (next == RetryConnection)
            {
                password = null;
                break;
            }
        }
    }

    // Remember the connection right away, so it is not lost when the run is cancelled or fails later.
    settings.Server = options.Server;
    settings.Database = options.Database;
    settings.User = options.User;
    settings.TrustServerCertificate = options.TrustServerCertificate;
    settings.Save(settingsPath);

    // What to script.
    options.SingleFile = AnsiConsole.Confirm(
        "Write everything into a single file? [grey](no = one file per object, in a folder per type)[/]", settings.SingleFile);
    options.Content = AnsiConsole.Prompt(new TextPrompt<Content>("Script the schema, the data, or both?")
        .AddChoices([Content.Schema, Content.Data, Content.All])
        .WithConverter(c => c.ToString().ToLowerInvariant())
        .DefaultValue(settings.Content));

    if (!AskObjects(options, settings, server))
    {
        exitCode = 1;
        return null;
    }

    options.CreateOrAlter = options.IncludeSchema && new[] { "SP", "UDF", "Views" }.Any(options.IncludesFolder)
        ? AnsiConsole.Confirm("Write procedures, functions and views as CREATE OR ALTER? [grey](no = CREATE)[/]", settings.CreateOrAlter)
        // Nothing it applies to this time: keep the remembered answer for the next run.
        : settings.CreateOrAlter;

    if (options.IncludeData && !options.SingleFile)
    {
        while (true)
        {
            var dataFolder = AskText("Folder for the data files", settings.DataFolder.Length > 0 ? settings.DataFolder : "Data");
            if (Options.DataFolderError(dataFolder) is not { } error)
            {
                options.DataFolder = dataFolder;
                break;
            }

            AnsiConsole.MarkupLine($"[red]{Markup.Escape(error)}[/]");
        }
    }

    // Where to.
    if (options.SingleFile)
    {
        var databaseFile = SafeFileName($"{options.Database}.sql");
        // The last file again - but one named after the last run's database follows the database chosen now (same
        // folder), so exporting another database does not overwrite that one's file.
        var suggested = settings.OutputFile.Length == 0
            ? Path.Combine(settings.Output.Length > 0 ? settings.Output : Environment.CurrentDirectory, databaseFile)
            : Path.GetFileName(settings.OutputFile).Equals(SafeFileName($"{previousDatabase}.sql"), StringComparison.OrdinalIgnoreCase)
                ? Path.Combine(Path.GetDirectoryName(settings.OutputFile)!, databaseFile)
                : settings.OutputFile;
        // A folder (an existing one, or a name without .sql) gets <database>.sql inside it, like -o.
        options.OutputFile = AskPath("Output file [grey](a .sql file, or a folder for <database>.sql)[/]", suggested, Path.GetDirectoryName,
            path => Directory.Exists(path) || !path.EndsWith(".sql", StringComparison.OrdinalIgnoreCase) ? Path.Combine(path, databaseFile) : path);
        options.Output = Path.GetDirectoryName(options.OutputFile)!;
    }
    else
    {
        options.Output = AskPath("Output folder [grey](e.g. the repo's Database folder)[/]",
            settings.Output.Length > 0 ? settings.Output : Environment.CurrentDirectory, path => path);
    }

    settings.SingleFile = options.SingleFile;
    settings.Content = options.Content;
    settings.CreateOrAlter = options.CreateOrAlter;
    if (options.IncludeData && !options.SingleFile)
    {
        // Only when it was asked: otherwise options.DataFolder is the default and would replace the remembered one.
        settings.DataFolder = options.DataFolder;
    }

    if (options.SingleFile)
    {
        settings.OutputFile = options.OutputFile;
    }
    else
    {
        settings.Output = options.Output;
    }

    settings.Save(settingsPath);

    AnsiConsole.WriteLine();
    if (!AnsiConsole.Confirm("Start?", defaultValue: true))
    {
        AnsiConsole.MarkupLine("[grey]Cancelled.[/]");
        return null;
    }

    return server;
}

// What to script: the entire database, or specific objects from one list grouped by type.
// The choice covers the schema and the data alike (data only: just the tables are listed). Remembered per type;
// a type whose objects were all chosen also includes the ones added later. Returns false when the objects could
// not be listed.
static bool AskObjects(Options options, Settings settings, Server server)
{
    string[] folders = options.IncludeSchema ? Options.SchemaFolders : ["Table"];
    // Data-only runs (just tables) keep their own choice, so they do not replace the one of schema runs.
    var remembered = options.IncludeSchema ? settings.Objects : settings.DataObjects;
    void Remember(Dictionary<string, List<string>>? choice)
    {
        if (options.IncludeSchema)
        {
            settings.Objects = choice;
        }
        else
        {
            settings.DataObjects = choice;
        }
    }

    options.Picked = null;
    var entire = AnsiConsole.Confirm(
        options.IncludeSchema ? "Script the entire database? [grey](no = choose the objects)[/]" : "The data of all tables? [grey](no = choose the tables)[/]",
        remembered is null);
    if (entire)
    {
        Remember(null);
        return true;
    }

    Dictionary<string, List<string>> names = [];
    string? error = null;
    AnsiConsole.Status().Start("Reading the object list ...", _ =>
    {
        try
        {
            var database = server.Databases[options.Database]
                ?? throw new FailedOperationException($"Database '{options.Database}' not found.");
            foreach (var folder in folders)
            {
                names[folder] = ObjectsIn(database, folder)
                    .Select(o => ObjectKey(o.Schema, o.Name))
                    .Order(StringComparer.OrdinalIgnoreCase)
                    .ToList();
            }
        }
        catch (Exception ex) when (IsSqlError(ex))
        {
            error = ex.GetBaseException().Message;
        }
    });

    if (error is not null)
    {
        AnsiConsole.MarkupLine($"[red]Could not list the objects:[/] {Markup.Escape(error)}");
        return false;
    }

    // The choice so far per type. Coming from "entire database" everything is ticked, to untick what is not wanted.
    var available = folders.Where(f => names[f].Count > 0).ToList();
    Dictionary<string, HashSet<string>> chosen = [];
    foreach (var folder in available)
    {
        HashSet<string>? before = remembered is null ? null
            : remembered.TryGetValue(folder, out var list) ? list.ToHashSet(StringComparer.OrdinalIgnoreCase) : [];
        chosen[folder] = names[folder]
            .Where(n => before is null || before.Contains("*") || before.Contains(n))
            .ToHashSet(StringComparer.OrdinalIgnoreCase);
    }

    // Collapsed by type: the types with how much of each is chosen; picking one opens the list of its objects.
    const string Done = "";
    while (true)
    {
        var next = AnsiConsole.Prompt(new SelectionPrompt<string>()
            .Title("Which objects? [grey](pick a type to choose its objects)[/]")
            .PageSize(10)
            .UseConverter(f => f == Done ? "[green]Done[/]" : $"{FolderTitle(f),-26} [grey]{ChosenText(chosen[f].Count, names[f].Count)}[/]")
            .AddChoices([.. available, Done]));
        if (next == Done)
        {
            if (chosen.Values.Any(c => c.Count > 0))
            {
                break;
            }

            AnsiConsole.MarkupLine("[yellow]Choose at least one object.[/]");
            continue;
        }

        // The first row ("" = all of them) selects or clears the whole type at once.
        var prompt = new MultiSelectionPrompt<string>()
            .Title($"{FolderTitle(next)}:")
            .InstructionsText("[grey](space toggles - on the first row for all of them, enter goes back to the types)[/]")
            .NotRequired()
            .PageSize(20)
            .UseConverter(n => n.Length == 0 ? $"[bold]All {FolderTitle(next).ToLowerInvariant()}[/] [grey]({names[next].Count})[/]" : Markup.Escape(n))
            .AddChoiceGroup("", names[next]);
        foreach (var name in chosen[next])
        {
            prompt.Select(name);
        }

        chosen[next] = AnsiConsole.Prompt(prompt).Where(n => n.Length > 0).ToHashSet(StringComparer.OrdinalIgnoreCase);
    }

    options.Picked = new(StringComparer.OrdinalIgnoreCase);
    Dictionary<string, List<string>> choice = [];
    List<string> summary = [];
    foreach (var folder in available.Where(f => chosen[f].Count > 0))
    {
        // All of a type is kept as "*", so objects added later are included too.
        List<string> stored = chosen[folder].Count == names[folder].Count ? ["*"] : [.. chosen[folder].Order(StringComparer.OrdinalIgnoreCase)];
        options.Picked[folder] = stored.ToHashSet(StringComparer.OrdinalIgnoreCase);
        choice[folder] = stored;
        summary.Add($"{FolderTitle(folder)} ({ChosenText(chosen[folder].Count, names[folder].Count)})");
    }

    Remember(choice);

    AnsiConsole.MarkupLine($"Objects: [blue]{Markup.Escape(string.Join(", ", summary))}[/]");
    return true;
}

static string ChosenText(int chosen, int total) => chosen == total ? $"all {total}" : chosen == 0 ? "none" : $"{chosen} of {total}";

// The objects of one type (schema folder), without system objects.
static IEnumerable<ScriptSchemaObjectBase> ObjectsIn(Database database, string folder) => folder switch
{
    "Table" => database.Tables.Cast<Table>().Where(t => !t.IsSystemObject),
    "SP" => database.StoredProcedures.Cast<StoredProcedure>().Where(p => !p.IsSystemObject),
    "UDF" => database.UserDefinedFunctions.Cast<UserDefinedFunction>().Where(f => !f.IsSystemObject),
    "UDT" => database.UserDefinedTableTypes.Cast<UserDefinedTableType>(),
    "Views" => database.Views.Cast<View>().Where(v => !v.IsSystemObject),
    _ => [],
};

// Connects to the server (master) and lists its online user databases. ConnectError: the connection failed.
// ListError: connected, but the list could not be read (the database name is then typed in).
static (List<string> Databases, string? ConnectError, string? ListError) ListDatabases(Options options)
{
    List<string> databases = [];
    string? connectError = null;
    string? listError = null;
    AnsiConsole.Status().Start($"Connecting to {Markup.Escape(options.Server)} ...", _ =>
    {
        Server master;
        try
        {
            master = Connect(options, null);
        }
        catch (Exception ex) when (IsSqlError(ex))
        {
            connectError = ex.GetBaseException().Message;
            return;
        }

        try
        {
            // A plain query rather than SMO's database properties: Azure SQL does not provide some of them
            // (e.g. IsAccessible) from master, and then SMO cannot load the list at all.
            var rows = master.ConnectionContext.ExecuteWithResults(
                "SELECT name FROM sys.databases WHERE name NOT IN (N'master', N'tempdb', N'model', N'msdb') AND state = 0").Tables[0].Rows;
            databases = rows.Cast<System.Data.DataRow>()
                .Select(r => (string)r[0])
                .Order(StringComparer.OrdinalIgnoreCase)
                .ToList();
        }
        catch (Exception ex) when (IsSqlError(ex))
        {
            listError = ex.GetBaseException().Message;
        }
        finally
        {
            master.ConnectionContext.Disconnect();
        }
    });

    return (databases, connectError, listError);
}

static (Server? Server, string? Error) OpenDatabase(Options options)
{
    Server? server = null;
    string? error = null;
    AnsiConsole.Status().Start($"Opening {Markup.Escape(options.Database)} ...", _ =>
    {
        try
        {
            server = Connect(options, options.Database);
        }
        catch (Exception ex) when (IsSqlError(ex))
        {
            error = ex.GetBaseException().Message;
        }
    });

    return (server, error);
}

static string AskText(string label, string suggested)
{
    var prompt = new TextPrompt<string>($"{label}:");
    if (suggested.Length > 0)
    {
        prompt.DefaultValue(suggested);
    }

    return AnsiConsole.Prompt(prompt).Trim();
}

// Asks for a path (full path returned); offers to create the folder (directoryOf) when it does not exist.
// resolve turns the answer into the path to use (shown when it differs).
static string AskPath(string label, string suggested, Func<string, string?> directoryOf, Func<string, string>? resolve = null)
{
    while (true)
    {
        var answer = Path.GetFullPath(AskText(label, suggested));
        var path = resolve?.Invoke(answer) ?? answer;
        if (path != answer)
        {
            AnsiConsole.MarkupLine($"  [grey]->[/] [blue]{Markup.Escape(path)}[/]");
        }

        var directory = directoryOf(path);
        if (directory is null || Directory.Exists(directory)
            || AnsiConsole.Confirm($"[yellow]{Markup.Escape(directory)} does not exist.[/] Create it?", defaultValue: false))
        {
            return path;
        }

        suggested = path;
    }
}

static string ContentText(Content content) => content switch
{
    Content.Schema => "the schema",
    Content.Data => "the data",
    _ => "the schema and data",
};

// Errors from SQL Server or SMO (connection, permissions, ...) - shown as a message, not a stack trace.
static bool IsSqlError(Exception ex) => ex is SmoException or ConnectionException or SqlException;

// A schema folder's name in the object list.
static string FolderTitle(string folder) => folder switch
{
    "Table" => "Tables",
    "SP" => "Stored procedures",
    "UDF" => "User-defined functions",
    "UDT" => "User-defined table types",
    "Views" => "Views",
    _ => folder,
};

// A progress bar that waits for its turn. Its name stays the same; what it is doing shows in the StatusColumn.
static ProgressTask AddTask(ProgressContext progress, string name)
{
    var task = progress.AddTask(Markup.Escape(name), autoStart: false);
    task.State.Update<TaskPhase>(StatusColumn.PhaseKey, _ => TaskPhase.Waiting);
    return task;
}

// Starts the task as "reading from the database" (an animated, unknown amount).
static void Begin(ProgressTask task)
{
    task.StartTask();
    task.IsIndeterminate = true;
    task.State.Update<TaskPhase>(StatusColumn.PhaseKey, _ => TaskPhase.Reading);
}

// Switches the task from "unknown amount" to counting up to total.
static void Measure(ProgressTask task, double total, Unit unit = Unit.Objects)
{
    task.IsIndeterminate = false;
    task.MaxValue = Math.Max(total, 1);
    task.State.Update<double>(StatusColumn.TotalKey, _ => total);
    task.State.Update<Unit>(StatusColumn.UnitKey, _ => unit);
    task.State.Update<TaskPhase>(StatusColumn.PhaseKey, _ => TaskPhase.Counting);
}

// A step that does not run because an earlier one failed.
static void Skip(ProgressTask? task)
{
    if (task is null)
    {
        return;
    }

    task.StopTask();
    task.State.Update<TaskPhase>(StatusColumn.PhaseKey, _ => TaskPhase.Skipped);
}

static void Finish(ProgressTask task)
{
    task.IsIndeterminate = false;
    task.Value = task.MaxValue;
    task.StopTask();
    task.State.Update<TaskPhase>(StatusColumn.PhaseKey, _ => TaskPhase.Done);
}

// A table's estimated row count (from its statistics), at least 1, as its share of the data bar.
static long Weight(Table table) => Math.Max(table.RowCount, 1);

static string ObjectKey(string schema, string name) => $"{schema}.{name}";

static void PrintReport(Report report, TimeSpan elapsed)
{
    var summary = new SpectreTable().Border(TableBorder.Rounded)
        .AddColumns("Folder", "Added", "Updated", "Renamed", "Deleted", "Unchanged", "Failed");
    summary.Columns[0].NoWrap();
    for (var i = 1; i < summary.Columns.Count; i++)
    {
        summary.Columns[i].RightAligned();
    }

    (Outcome Outcome, string Color)[] counted =
    [
        (Outcome.Added, "green"), (Outcome.Updated, "yellow"), (Outcome.Renamed, "blue"), (Outcome.Deleted, "red"),
        (Outcome.Unchanged, "default"), (Outcome.Failed, "red"),
    ];
    // Only folders with something to count: e.g. not the run-wide --objects warnings, which have no folder.
    var folders = report.Entries.Where(e => counted.Any(c => c.Outcome == e.Outcome)).Select(e => e.Folder).Distinct();
    foreach (var folder in folders)
    {
        var cells = counted.Select(c => report.Count(c.Outcome, folder) is var n and > 0 ? $"[{c.Color}]{n}[/]" : "[grey]0[/]");
        summary.AddRow([folder.Length > 0 ? Markup.Escape(folder) : "Single file", .. cells]);
    }

    AnsiConsole.WriteLine();
    AnsiConsole.Write(summary);

    var notable = report.Entries.Where(e => e.Outcome is not (Outcome.Unchanged or Outcome.Orphan)).ToList();
    if (notable.Count > 0)
    {
        AnsiConsole.WriteLine();
        foreach (var entry in notable)
        {
            var (label, color) = entry.Outcome switch
            {
                Outcome.Added => ("added", "green"),
                Outcome.Updated => ("updated", "yellow"),
                Outcome.Renamed => ("renamed", "blue"),
                Outcome.Deleted => ("deleted", "red"),
                Outcome.Skipped => ("skipped", "grey"),
                Outcome.Warning => ("warning", "yellow"),
                _ => ("FAILED", "red bold"),
            };
            var name = entry.Folder.Length > 0 ? $"{entry.Folder}/{entry.File}" : entry.File;
            var detail = entry.Detail is null ? "" : $" [grey]({Markup.Escape(entry.Detail)})[/]";
            AnsiConsole.MarkupLine($"  [{color}]{label,-8}[/] {Markup.Escape(name)}{detail}");
        }
    }

    var written = report.Count(Outcome.Added) + report.Count(Outcome.Updated) + report.Count(Outcome.Renamed);
    AnsiConsole.WriteLine();
    AnsiConsole.MarkupLine($"Done in {elapsed.TotalSeconds:0.0}s: [green]{written} written[/], {report.Count(Outcome.Unchanged)} unchanged, "
        + $"{report.Count(Outcome.Deleted)} pruned, {(report.Count(Outcome.Failed) is var failed and > 0 ? $"[red]{failed} failed[/]" : "0 failed")}.");
}

static Server Connect(Options options, string? databaseName)
{
    var server = new Server(new ServerConnection(new SqlConnection(BuildConnectionString(options, databaseName))));
    // Load the properties the lists filter on together with the lists, instead of one query per object.
    // (Databases are listed with a plain query, see ListDatabases.)
    server.SetDefaultInitFields(typeof(Table), nameof(Table.IsSystemObject), nameof(Table.RowCount));
    server.SetDefaultInitFields(typeof(StoredProcedure), nameof(StoredProcedure.IsSystemObject));
    server.SetDefaultInitFields(typeof(UserDefinedFunction), nameof(UserDefinedFunction.IsSystemObject));
    server.SetDefaultInitFields(typeof(View), nameof(View.IsSystemObject));
    // No limit per query (SMO's default is 10 minutes): reading a big table or the definitions of a big database
    // over a slow connection may take longer. Ctrl+C still stops the run.
    server.ConnectionContext.StatementTimeout = 0;
    server.ConnectionContext.Connect();
    return server;
}

// Generated files in a folder (only <schema>.<name>.<suffix>.sql), keyed case-insensitively by file name.
static Dictionary<string, string> ExistingFiles(string directory, string suffix)
{
    Dictionary<string, string> files = new(StringComparer.OrdinalIgnoreCase);
    if (!Directory.Exists(directory))
    {
        return files;
    }

    var ending = $".{suffix}.sql";
    foreach (var path in Directory.EnumerateFiles(directory))
    {
        var name = Path.GetFileName(path);
        // schema.name.suffix.sql: at least one dot before the suffix, e.g. not "Rollback_X.sql".
        if (name.EndsWith(ending, StringComparison.OrdinalIgnoreCase) && name[..^ending.Length].Contains('.'))
        {
            files[name] = path;
        }
    }

    return files;
}

static string FileName(string schema, string name, string suffix) => SafeFileName($"{schema}.{name}.{suffix}.sql");

static string SafeFileName(string name)
{
    var invalid = "<>:\"/\\|?*".ToCharArray();
    return string.Concat(name.Select(c => invalid.Contains(c) || char.IsControl(c) ? '_' : c));
}

// SMO ends most batches (CREATE TABLE, module text, ...) with a CRLF; drop exactly one so there is no blank
// line before GO. A module whose text ends in a bare LF keeps it, as does a blank line in the object's own text.
static void AppendBatches(TextWriter writer, StringCollection batches)
{
    foreach (var batch in batches.Cast<string>())
    {
        writer.Write(batch.EndsWith(Eol) ? batch[..^Eol.Length] : batch);
        writer.Write($"{Eol}GO{Eol}");
    }
}

// Compares two files without loading them: line by line, or (ignoreLineOrder) as a set of lines in any order.
// allHeaders: ignore the Script Date of every object header (single file), not only the one in the first line.
static bool SameContent(string existingPath, string newPath, bool ignoreLineOrder, bool allHeaders) =>
    ignoreLineOrder
        ? Fingerprint(ComparableLines(existingPath, allHeaders)) == Fingerprint(ComparableLines(newPath, allHeaders))
        : ComparableLines(existingPath, allHeaders).SequenceEqual(ComparableLines(newPath, allHeaders), StringComparer.Ordinal);

// A file's lines, read as they are needed. Split at CRLF only, so a bare LF (in module text) stays inside its
// line and a change from LF to CRLF still counts. The Script Date is ignored: that of the header in the first
// line (one file per object), or of every header (allHeaders, single file).
static IEnumerable<string> ComparableLines(string path, bool allHeaders)
{
    // Detects the encoding from the BOM, like File.ReadAllText (UTF-8 without one).
    using var reader = new StreamReader(path, detectEncodingFromByteOrderMarks: true);
    var buffer = new char[65536];
    // The current line so far (it may continue from one block into the next, even between \r and \n).
    var line = new StringBuilder();
    var first = true;
    int read;
    while ((read = reader.Read(buffer, 0, buffer.Length)) > 0)
    {
        var start = 0;
        for (var i = 0; i < read; i++)
        {
            // A CRLF: the \r is just before, in this block or at the end of the line carried over.
            if (buffer[i] != '\n' || (i > start ? buffer[i - 1] != '\r' : line.Length == 0 || line[line.Length - 1] != '\r'))
            {
                continue;
            }

            line.Append(buffer, start, i - start);
            line.Length--;
            start = i + 1;
            var text = line.ToString();
            line.Clear();
            // One file per object: the header line is left out of the comparison altogether.
            if (allHeaders || !first || !text.StartsWith("/****** Object:", StringComparison.Ordinal))
            {
                yield return allHeaders ? WithoutScriptDate(text) : text;
            }

            first = false;
        }

        line.Append(buffer, start, read - start);
    }

    // What follows the last CRLF (empty when the file ends with one).
    yield return allHeaders ? WithoutScriptDate(line.ToString()) : line.ToString();
}

// Only header lines can have a Script Date, so the others skip the regex.
static string WithoutScriptDate(string line) =>
    line.StartsWith("/******", StringComparison.Ordinal)
        ? Regex.Replace(line, @"^(/\*{6} Object: .*?)\s+Script Date: [^*\r\n]*\*{6}/", "$1 ******/")
        : line;

// An order-independent fingerprint of lines: the count and the sums of the two 64-bit halves of each line's
// 128-bit xxHash (fast; not a security hash, which is not needed to spot a changed file). Two files with the
// same lines in any order (duplicates included) get the same one.
static (long Count, ulong A, ulong B) Fingerprint(IEnumerable<string> lines)
{
    long count = 0;
    ulong a = 0;
    ulong b = 0;
    foreach (var line in lines)
    {
        var hash = XxHash128.HashToUInt128(MemoryMarshal.AsBytes(line.AsSpan()));
        a += (ulong)(hash >> 64);
        b += (ulong)hash;
        count++;
    }

    return (count, a, b);
}

static void CopyText(TextReader reader, TextWriter writer)
{
    var buffer = new char[81920];
    int read;
    while ((read = reader.Read(buffer, 0, buffer.Length)) > 0)
    {
        writer.Write(buffer, 0, read);
    }
}

