sealed class Options
{
    public const string PasswordEnvVar = "DB_EXPORT_PASSWORD";

    public static readonly string[] SchemaFolders = ["Table", "SP", "UDF", "UDT", "Views"];

    // The app's version, e.g. 1.2.0 (0.0.0-dev for local builds), without the "+<commit>" the build may add.
    public static readonly string Version =
        (typeof(Options).Assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion ?? "0.0.0-dev").Split('+')[0];

    public string Server { get; set; } = "";
    public string Database { get; set; } = "";
    public string User { get; set; } = "";
    // Never parsed from the arguments: read from DB_EXPORT_PASSWORD or prompted for.
    public string Password { get; set; } = "";
    public bool TrustServerCertificate { get; set; }
    // One file per object: the root folder. Single file: the folder of <database>.sql, unless OutputFile is set.
    public string Output { get; set; } = ".";
    public string OutputFile { get; set; } = "";
    public bool SingleFile { get; set; }
    public Content Content { get; set; } = Content.Schema;
    public string DataFolder { get; set; } = "Data";
    public bool Prune { get; set; }
    public bool CreateOrAlter { get; set; }
    // --version: print the version and exit.
    public bool ShowVersion { get; set; }
    // What to script (the same choice for the schema and the data):
    // --only: the object types; empty = all.
    public HashSet<string> Only { get; } = new(StringComparer.OrdinalIgnoreCase);
    // --objects: only these objects ("schema.name", any type); empty = all.
    public HashSet<string> Objects { get; } = new(StringComparer.OrdinalIgnoreCase);
    // Interactive: the chosen objects per type ("schema.name" or "*" for all); a missing type has none; null = all.
    public Dictionary<string, HashSet<string>>? Picked { get; set; }

    public bool IncludeSchema => Content != Content.Data;
    public bool IncludeData => Content != Content.Schema;

    // Whether anything of this type (schema folder) can be chosen.
    public bool IncludesFolder(string folder) => (Only.Count == 0 || Only.Contains(folder)) && (Picked is null || Picked.ContainsKey(folder));

    public bool Selected(string folder, string schema, string name)
    {
        var key = $"{schema}.{name}";
        return IncludesFolder(folder)
            && (Objects.Count == 0 || Objects.Contains(key))
            && (Picked is null || Picked[folder].Contains("*") || Picked[folder].Contains(key));
    }

    // Why the name cannot be the data folder, or null when it can.
    public static string? DataFolderError(string name) =>
        name.Length == 0 || name.IndexOfAny(Path.GetInvalidFileNameChars()) >= 0 || name is "." or ".."
            ? $"'{name}' is not a valid folder name."
            : SchemaFolders.Contains(name, StringComparer.OrdinalIgnoreCase)
                ? $"'{name}' is used for the {name} scripts; choose another folder for the data."
                : null;

    // Returns null when --help was requested.
    public static Options? Parse(string[] args)
    {
        var options = new Options();
        var dataFolderSet = false;
        for (var i = 0; i < args.Length; i++)
        {
            var arg = args[i];
            // A value never starts with '-', so "-o -d x" fails instead of using "-d" as the folder.
            string Value() => i + 1 < args.Length && !args[i + 1].StartsWith('-')
                ? args[++i]
                : throw new ArgumentException($"{arg} needs a value.");

            // A comma separated list. PowerShell passes an unquoted a,b as separate arguments, so the following
            // non-option arguments belong to the list too.
            List<string> Values()
            {
                List<string> values = [Value()];
                while (i + 1 < args.Length && !args[i + 1].StartsWith('-'))
                {
                    values.Add(args[++i]);
                }

                return [.. values.SelectMany(v => v.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))];
            }

            switch (arg)
            {
                case "-h" or "--help" or "-?":
                    return null;
                case "--version":
                    // Needs nothing else (no --server etc.).
                    options.ShowVersion = true;
                    return options;
                case "-S" or "--server":
                    options.Server = Value();
                    break;
                case "-d" or "--database":
                    options.Database = Value();
                    break;
                case "-U" or "--user":
                    options.User = Value();
                    break;
                case "--trust-server-certificate":
                    options.TrustServerCertificate = true;
                    break;
                case "-o" or "--output":
                    options.Output = Value();
                    break;
                case "--single-file":
                    options.SingleFile = true;
                    break;
                case "--content":
                    var content = Value();
                    options.Content = Enum.TryParse<Content>(content, ignoreCase: true, out var parsed) && Enum.IsDefined(parsed)
                        ? parsed
                        : throw new ArgumentException($"--content: unknown value '{content}' (use schema, data or all).");
                    break;
                case "--objects":
                    foreach (var name in Values())
                    {
                        options.Objects.Add(ParseObjectName(name));
                    }

                    break;
                case "--data-folder":
                    options.DataFolder = Value();
                    dataFolderSet = true;
                    if (DataFolderError(options.DataFolder) is { } error)
                    {
                        throw new ArgumentException($"--data-folder: {error}");
                    }

                    break;
                case "--create-or-alter":
                    options.CreateOrAlter = true;
                    break;
                case "--prune":
                    options.Prune = true;
                    break;
                case "--no-pause":
                    // Handled before parsing (pauseAtExit).
                    break;
                case "--only":
                    foreach (var folder in Values())
                    {
                        options.Only.Add(SchemaFolders.FirstOrDefault(f => f.Equals(folder, StringComparison.OrdinalIgnoreCase))
                            ?? throw new ArgumentException($"--only: unknown object type '{folder}' (use {string.Join(", ", SchemaFolders)})."));
                    }

                    break;
                default:
                    throw new ArgumentException($"unknown argument '{arg}'.");
            }
        }

        if (options.Server.Length == 0 || options.Database.Length == 0 || options.User.Length == 0)
        {
            throw new ArgumentException("--server, --database and --user are required.");
        }

        if (!options.IncludeData && dataFolderSet)
        {
            throw new ArgumentException("--data-folder needs the data (--content data or all).");
        }

        if (!options.IncludeSchema && options.CreateOrAlter)
        {
            throw new ArgumentException("--create-or-alter needs the schema (--content schema or all).");
        }

        if (!options.IncludeSchema && options.Only.Count > 0 && !options.Only.Contains("Table"))
        {
            throw new ArgumentException("--content data only scripts tables; add Table to --only (or leave --only out).");
        }

        if (options.SingleFile && (options.Prune || dataFolderSet))
        {
            throw new ArgumentException("--prune and --data-folder are for one file per object, not --single-file.");
        }

        if (options.SingleFile && options.Output.EndsWith(".sql", StringComparison.OrdinalIgnoreCase))
        {
            // -o names the file itself.
            options.OutputFile = options.Output;
            options.Output = Path.GetDirectoryName(Path.GetFullPath(options.Output))!;
        }

        return options;
    }

    // "schema.name", "[schema].[name]" or "name" (dbo), as "schema.name".
    static string ParseObjectName(string name)
    {
        var parts = name.Split('.', 2, StringSplitOptions.TrimEntries)
            .Select(p => p.StartsWith('[') && p.EndsWith(']') ? p[1..^1] : p)
            .ToArray();
        if (parts.Any(p => p.Length == 0))
        {
            throw new ArgumentException($"--objects: invalid object name '{name}'.");
        }

        return parts.Length == 2 ? $"{parts[0]}.{parts[1]}" : $"dbo.{parts[0]}";
    }

