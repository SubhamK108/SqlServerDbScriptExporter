sealed class StatusColumn : ProgressColumn
{
    public const string PhaseKey = "phase";
    public const string TotalKey = "total";
    public const string UnitKey = "unit";

    protected override bool NoWrap => true;

    public override int? GetColumnWidth(RenderOptions options) => 30;

    public override IRenderable Render(RenderOptions options, ProgressTask task, TimeSpan deltaTime)
    {
        var total = task.State.Get<double>(TotalKey);
        var unit = task.State.Get<Unit>(UnitKey);
        var unitName = unit switch
        {
            Unit.Rows => "rows",
            Unit.Tables => total == 1 ? "table" : "tables",
            _ => total == 1 ? "object" : "objects",
        };
        var approximate = unit == Unit.Rows ? "~" : "";
        return new Markup(task.State.Get<TaskPhase>(PhaseKey) switch
        {
            TaskPhase.Waiting => "[grey]waiting[/]",
            TaskPhase.Reading => "[yellow]reading from the database[/]",
            TaskPhase.Counting => $"{approximate}{task.Value:N0} / {total:N0} {unitName} [grey]{task.Percentage:0}%[/]",
            // Only a counted task has a total to show (reading and ordering steps have none).
            TaskPhase.Done when total > 0 && unit != Unit.Rows =>$"[green]done[/] [grey]{total:N0} {unitName}[/]",
            TaskPhase.Done => "[green]done[/]",
            TaskPhase.Skipped => "[grey]skipped[/]",
            _ => "[red]failed[/]",
        });
    }
}

